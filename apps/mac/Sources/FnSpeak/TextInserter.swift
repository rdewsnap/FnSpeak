import AppKit
import ApplicationServices

/// Puts text into whatever app has focus.
///
/// Default is paste: copy to the clipboard, press ⌘V, then restore what was
/// there. It works almost everywhere. Apps where it doesn't can be switched
/// to direct Accessibility insertion or simulated typing in settings.
enum TextInserter {
    enum Method: String {
        case paste, ax, type
    }

    static func insert(_ text: String, bundleId: String?) {
        guard !text.isEmpty else { return }
        let override = bundleId.flatMap { Preferences.shared.insertionOverrides[$0] }.flatMap(Method.init(rawValue:))
        switch override ?? .paste {
        case .paste:
            paste(text)
        case .ax:
            if !insertViaAccessibility(text) { paste(text) }
        case .type:
            type(text)
        }
    }

    /// Press Return, e.g. to send a message after dictating it. The delay
    /// lets the target app take in a paste first.
    static func pressReturn(after delay: TimeInterval = 0.15) {
        DispatchQueue.main.asyncAfter(deadline: .now() + delay) {
            postKey(36, flags: []) // ↩
        }
    }

    /// Select the previous `count` characters and replace them with `text`.
    /// Used by the swap-to-raw shortcut right after a dictation.
    static func replacePrevious(_ count: Int, with text: String) {
        for _ in 0..<count {
            postKey(123, flags: .maskShift) // ←
        }
        paste(text)
    }

    // MARK: - Methods

    // Markers from nspasteboard.org that ask clipboard managers (Maccy,
    // Paste, Raycast, Alfred…) not to record an entry. Different apps honour
    // different ones, so all three go on.
    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// Seconds before the clipboard is put back after pasting. Not in the UI:
    /// `defaults write com.fnspeak.FnSpeak clipboardRestoreDelay -float 1`
    /// for an app that still pastes the old clipboard.
    private static var restoreDelay: TimeInterval {
        let value = UserDefaults.standard.object(forKey: "clipboardRestoreDelay") as? Double ?? 0.6
        return min(max(value, 0.1), 5)
    }

    private static func paste(_ text: String) {
        let pb = NSPasteboard.general
        let saved = snapshot(pb)

        pb.clearContents()
        pb.declareTypes([.string, transient, concealed, autoGenerated], owner: nil)
        pb.setString(text, forType: .string)
        for marker in [transient, concealed, autoGenerated] { pb.setData(Data(), forType: marker) }
        let changeCount = pb.changeCount

        postKey(9, flags: .maskCommand) // ⌘V

        // Slow apps read the clipboard well after ⌘V; restoring too soon
        // pastes the old contents.
        DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay) {
            // Don't clobber something the user copied in the meantime.
            guard pb.changeCount == changeCount else { return }
            pb.clearContents()
            if !saved.isEmpty { pb.writeObjects(saved) }
        }
    }

    private static func insertViaAccessibility(_ text: String) -> Bool {
        let system = AXUIElementCreateSystemWide()
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let element = focused else { return false }
        // swiftlint:disable:next force_cast
        let el = element as! AXUIElement
        return AXUIElementSetAttributeValue(el, kAXSelectedTextAttribute as CFString, text as CFString) == .success
    }

    private static func type(_ text: String) {
        let source = CGEventSource(stateID: .combinedSessionState)
        let utf16 = Array(text.utf16)
        var index = 0
        while index < utf16.count {
            let chunk = Array(utf16[index..<min(index + 20, utf16.count)])
            for down in [true, false] {
                let event = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: down)
                event?.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: chunk)
                event?.post(tap: .cghidEventTap)
            }
            index += 20
            usleep(4_000)
        }
    }

    private static func postKey(_ key: CGKeyCode, flags: CGEventFlags) {
        let source = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: down)
            event?.flags = flags
            event?.post(tap: .cghidEventTap)
        }
    }

    private static func snapshot(_ pb: NSPasteboard) -> [NSPasteboardItem] {
        (pb.pasteboardItems ?? []).map { item in
            let copy = NSPasteboardItem()
            for type in item.types {
                if let data = item.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy
        }
    }
}
